def seed_source_catalog(db: Session) -> None:
    pending = {"nc_abc"}
    manual = {"nc_contractors", "nc_food_inspections", "nc_workers_comp", "sc_sos", "sc_abl", "sc_food_grades", "sc_workers_comp", "va_scc", "va_workers_comp"}
    credential_sources = {"google_places_ids", "hunter", "email_verifier", "openai_web_research", "sam_gov"}
    for raw_item in SOURCE_CATALOG:
        item = dict(raw_item)
        commercial = bool(item.get("commercial"))
        automation_allowed = bool(item.get("automation_allowed"))
        item.setdefault("cost_class", "metered" if commercial else ("manual" if not automation_allowed else "open"))
        item.setdefault("credential_required", item["id"] in credential_sources)
        item.setdefault("overage_possible", commercial)
        item.setdefault("policy_status", "pending" if item["id"] in pending else ("manual_only" if item["id"] in manual else "approved"))
        source = db.get(SourceSpec, item["id"])
        if source is None:
            source = SourceSpec(**item)
            db.add(source)
        else:
            for key, value in item.items():
                setattr(source, key, value)
    db.commit()
